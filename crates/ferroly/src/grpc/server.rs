/// What a route needs to run one call.
struct CallCtx {
    metadata: Metadata,
    timeout: Option<Duration>,
    deadline: Option<Instant>,
    peer: Peer,
    body: BodyStream,
    receive: Receive,
    max_encoding: usize,
}

impl CallCtx {
    fn request<T>(self, message: T) -> Request<T> {
        Request::from_server(
            message,
            self.metadata,
            self.timeout,
            self.deadline.map(Instant::into_std),
            self.peer,
        )
    }
}

/// A route's result.
enum Reply {
    Unary {
        metadata: Metadata,
        frame: Vec<u8>,
        trailers: Metadata,
    },
    Stream {
        metadata: Metadata,
        source: Box<dyn FrameSource>,
        trailers: Metadata,
    },
}

type Route = Arc<dyn Fn(CallCtx) -> BoxFuture<'static, Result<Reply, Status>> + Send + Sync>;
type PanicHook = Arc<dyn Fn(&str, &str) + Send + Sync>;
type ShutdownHook = Arc<dyn Fn() + Send + Sync>;

/// Registers a service's methods with a [`GrpcServer`] — what the server
/// adapters generated by [`GrpcGenerator`](super::codegen::GrpcGenerator)
/// implement. Add one with [`GrpcServer::add_service`].
pub trait GrpcService {
    /// Adds this service's routes to `server`.
    fn register(self, server: GrpcServer) -> GrpcServer;
}

/// A gRPC server: dispatches each call by its path (`/package.Service/Method`)
/// to the handler registered for it. It is an [`HttpHandler`], so it runs on
/// the [`http`](crate::http) server with HTTP/2 enabled — cleartext h2c
/// (prior knowledge) or TLS with ALPN `h2`:
///
/// ```no_run
/// use std::sync::Arc;
/// use ferroly::grpc::{GrpcServer, Request, Response, Status};
/// use ferroly::http::{serve_with_config, Http2Config, ServerConfig};
///
/// #[derive(ferroly::proto::Message, Default)]
/// struct Ping {
///     #[proto(tag = 1)]
///     n: u32,
/// }
///
/// # async fn ex() -> Result<(), Box<dyn std::error::Error>> {
/// let server = GrpcServer::new().unary("/demo.Echo/Ping", |req: Request<Ping>| async move {
///     let n = req.into_inner().n;
///     if n == 0 {
///         return Err(Status::invalid_argument("n must not be zero"));
///     }
///     Ok(Response::new(Ping { n: n + 1 }))
/// });
/// let config = ServerConfig {
///     http2: Some(Http2Config::default()),
///     ..ServerConfig::default()
/// };
/// let listener = tokio::net::TcpListener::bind("127.0.0.1:50051").await?;
/// serve_with_config(listener, Arc::new(server), std::future::pending(), config).await?;
/// # Ok(())
/// # }
/// ```
///
/// What the server does on every call:
///
/// - Rejects a request that is not gRPC: over HTTP/1.1 with `400`, with a
///   content type other than `application/grpc` / `application/grpc+proto`
///   with `415`, a method other than `POST` with `405` (each with an
///   `INTERNAL` `grpc-status`) — unless a [`fallback`](Self::fallback)
///   handler takes non-gRPC requests.
/// - Answers an unknown service or method, and a request compressed with
///   anything but `identity`, `gzip` or `deflate`, with `UNIMPLEMENTED`.
///   Compressed requests are decoded (bounded by the message limit after
///   decompression); responses are always sent uncompressed (`identity`),
///   which every client accepts.
/// - Runs its [`interceptor`](Self::interceptor)s before the handler.
/// - Bounds every message by [`max_decoding_message_size`](Self::max_decoding_message_size)
///   and [`max_encoding_message_size`](Self::max_encoding_message_size)
///   (4 MiB each by default), and the memory a decoded request takes by
///   [`max_decoded_bytes`](Self::max_decoded_bytes): `RESOURCE_EXHAUSTED`
///   beyond.
/// - Enforces the client's `grpc-timeout`: when it passes the handler is
///   dropped (and a response stream abandoned) and the call ends with
///   `DEADLINE_EXCEEDED`.
/// - Turns a panic, in a handler or while a response stream is encoded,
///   into `INTERNAL` (reported to
///   [`on_handler_panic`](Self::on_handler_panic)).
/// - Accepts requests without `te: trailers`, as grpc-go does, unless
///   [`require_te_trailers`](Self::require_te_trailers) is set.
/// - Stops a handler, and makes its [`StreamSender`](super::StreamSender)s
///   fail, when the client cancels the call.
#[derive(Clone)]
pub struct GrpcServer {
    routes: HashMap<String, Route>,
    services: HashSet<String>,
    max_decoding: usize,
    max_decoded_bytes: Option<usize>,
    max_encoding: usize,
    fallback: Option<Arc<dyn HttpHandler>>,
    on_panic: Option<PanicHook>,
    interceptors: Vec<Arc<dyn Interceptor>>,
    require_te: bool,
    on_shutdown: Vec<ShutdownHook>,
}

impl fmt::Debug for GrpcServer {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut methods: Vec<&String> = self.routes.keys().collect();
        methods.sort();
        f.debug_struct("GrpcServer")
            .field("methods", &methods)
            .field("max_decoding_message_size", &self.max_decoding)
            .field("max_decoded_bytes", &self.max_decoded_bytes)
            .field("max_encoding_message_size", &self.max_encoding)
            .field("fallback", &self.fallback.is_some())
            .field("interceptors", &self.interceptors.len())
            .field("require_te_trailers", &self.require_te)
            .finish()
    }
}

impl Default for GrpcServer {
    fn default() -> Self {
        Self::new()
    }
}

/// The service name of a path `/package.Service/Method`.
fn service_of(path: &str) -> Option<(&str, &str)> {
    let rest = path.strip_prefix('/')?;
    let (service, method) = rest.split_once('/')?;
    if service.is_empty() || method.is_empty() || method.contains('/') {
        return None;
    }
    Some((service, method))
}

impl GrpcServer {
    /// A server with no methods and the default 4 MiB message limits.
    pub fn new() -> Self {
        GrpcServer {
            routes: HashMap::new(),
            services: HashSet::new(),
            max_decoding: DEFAULT_MAX_MESSAGE_SIZE,
            max_decoded_bytes: None,
            max_encoding: DEFAULT_MAX_MESSAGE_SIZE,
            fallback: None,
            on_panic: None,
            interceptors: Vec::new(),
            require_te: false,
            on_shutdown: Vec::new(),
        }
    }

    /// The most memory a decoded request message may take, as the protobuf
    /// decoder estimates it
    /// ([`Limits::max_decoded_bytes`](crate::proto::Limits::max_decoded_bytes));
    /// beyond, the call fails with `RESOURCE_EXHAUSTED`. Default 16 times the
    /// [decoding limit](Self::max_decoding_message_size), at least 1 MiB
    /// (64 MiB for the default 4 MiB): it stops a small request (a run of
    /// empty sub-messages, two bytes each on the wire) from expanding into
    /// gigabytes of structs.
    ///
    /// The budget is per message, not per server: every request decoded at
    /// once may hold it while its handler runs, so the worst case is about
    /// `connections × max_concurrent_streams × budget` (100 streams of the
    /// default 64 MiB is 6.4 GiB per connection). Lower it to what your
    /// messages need, and cap connections and streams
    /// ([`ServerConfig`](crate::http::ServerConfig)), when that matters.
    #[must_use]
    pub fn max_decoded_bytes(mut self, bytes: usize) -> Self {
        self.max_decoded_bytes = Some(bytes);
        self
    }

    /// Adds an [`Interceptor`], run before every call's handler (in the
    /// order added). It sees the request metadata, deadline and peer, may
    /// change the metadata the handler sees, and fails the call with its
    /// `Err` status without running the handler.
    #[must_use]
    pub fn interceptor(mut self, interceptor: impl Interceptor) -> Self {
        self.interceptors.push(Arc::new(interceptor));
        self
    }

    /// Rejects requests without `te: trailers` (`INTERNAL`, as grpc C-core
    /// does). Off by default: like grpc-go, the server serves them, since
    /// the header only says that the client understands trailers, which
    /// every gRPC client does.
    #[must_use]
    pub fn require_te_trailers(mut self, on: bool) -> Self {
        self.require_te = on;
        self
    }

    /// Runs `hook` when [`serve`](Self::serve)'s shutdown signal fires,
    /// before connections drain: how the health service ends its `Watch`
    /// streams so they do not hold the drain open.
    pub(crate) fn on_shutdown(mut self, hook: impl Fn() + Send + Sync + 'static) -> Self {
        self.on_shutdown.push(Arc::new(hook));
        self
    }

    /// The largest request message accepted (default 4 MiB); a larger one
    /// fails the call with `RESOURCE_EXHAUSTED` before it is buffered.
    #[must_use]
    pub fn max_decoding_message_size(mut self, bytes: usize) -> Self {
        self.max_decoding = bytes;
        self
    }

    /// The largest response message sent (default 4 MiB); a handler that
    /// produces a larger one fails the call with `RESOURCE_EXHAUSTED`.
    #[must_use]
    pub fn max_encoding_message_size(mut self, bytes: usize) -> Self {
        self.max_encoding = bytes;
        self
    }

    /// Sends every request that is not gRPC (its content type is not
    /// `application/grpc…`) to `handler` instead of rejecting it — for
    /// example a `ferroly::turbo` router's
    /// `into_handler()`, to serve a REST API and gRPC on one port.
    #[must_use]
    pub fn fallback(mut self, handler: Arc<dyn HttpHandler>) -> Self {
        self.fallback = Some(handler);
        self
    }

    /// Called with the method path and the panic message when a handler or
    /// a server [interceptor](Self::interceptor) panics (the call ends with
    /// `INTERNAL`, whose message does not include the panic's). Keep it
    /// quick; a panic inside it is contained.
    #[must_use]
    pub fn on_handler_panic(mut self, hook: impl Fn(&str, &str) + Send + Sync + 'static) -> Self {
        self.on_panic = Some(Arc::new(hook));
        self
    }

    /// Adds a service's methods (for example a generated `…Server` adapter).
    #[must_use]
    pub fn add_service(self, service: impl GrpcService) -> Self {
        service.register(self)
    }

    /// Whether a handler is registered for `path` (`/package.Service/Method`).
    pub fn has_method(&self, path: &str) -> bool {
        self.routes.contains_key(path)
    }

    /// The fully qualified names of the services with at least one method.
    pub fn services(&self) -> impl Iterator<Item = &str> + '_ {
        self.services.iter().map(String::as_str)
    }

    fn route(mut self, path: &str, route: Route) -> Self {
        // Registration is programmer input: an invalid path is a bug.
        let Some((service, _)) = service_of(path) else {
            panic!("invalid gRPC method path {path:?}: expected /package.Service/Method");
        };
        self.services.insert(service.to_string());
        self.routes.insert(path.to_string(), route);
        self
    }

    /// Registers a unary method: one request, one response. A later
    /// registration for the same path replaces this one.
    ///
    /// # Panics
    ///
    /// When `path` is not of the form `/package.Service/Method`.
    #[must_use]
    pub fn unary<Req, Resp, F, Fut>(self, path: &str, handler: F) -> Self
    where
        Req: Message + Send + 'static,
        Resp: Message + Send + 'static,
        F: Fn(Request<Req>) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<Response<Resp>, Status>> + Send + 'static,
    {
        let handler = Arc::new(handler);
        self.route(
            path,
            Arc::new(move |mut ctx: CallCtx| {
                let handler = handler.clone();
                Box::pin(async move {
                    let message = read_one::<Req>(&mut ctx).await?;
                    let max = ctx.max_encoding;
                    let resp = handler(ctx.request(message)).await?;
                    unary_reply(resp, max)
                })
            }),
        )
    }

    /// Registers a server-streaming method: one request, a stream of
    /// responses.
    ///
    /// # Panics
    ///
    /// When `path` is not of the form `/package.Service/Method`.
    #[must_use]
    pub fn server_streaming<Req, Resp, F, Fut>(self, path: &str, handler: F) -> Self
    where
        Req: Message + Send + 'static,
        Resp: Message + Send + 'static,
        F: Fn(Request<Req>) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<Response<Streaming<Resp>>, Status>> + Send + 'static,
    {
        let handler = Arc::new(handler);
        self.route(
            path,
            Arc::new(move |mut ctx: CallCtx| {
                let handler = handler.clone();
                Box::pin(async move {
                    let message = read_one::<Req>(&mut ctx).await?;
                    let max = ctx.max_encoding;
                    let resp = handler(ctx.request(message)).await?;
                    Ok(stream_reply(resp, max))
                })
            }),
        )
    }

    /// Registers a client-streaming method: a stream of requests, one
    /// response.
    ///
    /// # Panics
    ///
    /// When `path` is not of the form `/package.Service/Method`.
    #[must_use]
    pub fn client_streaming<Req, Resp, F, Fut>(self, path: &str, handler: F) -> Self
    where
        Req: Message + Send + 'static,
        Resp: Message + Send + 'static,
        F: Fn(Request<Streaming<Req>>) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<Response<Resp>, Status>> + Send + 'static,
    {
        let handler = Arc::new(handler);
        self.route(
            path,
            Arc::new(move |ctx: CallCtx| {
                let handler = handler.clone();
                Box::pin(async move {
                    let max = ctx.max_encoding;
                    let resp = handler(request_stream(ctx)).await?;
                    unary_reply(resp, max)
                })
            }),
        )
    }

    /// Registers a bidirectional-streaming method: streams both ways, on
    /// one HTTP/2 stream. The handler typically spawns a task that reads the
    /// requests and feeds a [`Streaming::channel`], and returns its reading
    /// half at once.
    ///
    /// # Panics
    ///
    /// When `path` is not of the form `/package.Service/Method`.
    #[must_use]
    pub fn bidi_streaming<Req, Resp, F, Fut>(self, path: &str, handler: F) -> Self
    where
        Req: Message + Send + 'static,
        Resp: Message + Send + 'static,
        F: Fn(Request<Streaming<Req>>) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<Response<Streaming<Resp>>, Status>> + Send + 'static,
    {
        let handler = Arc::new(handler);
        self.route(
            path,
            Arc::new(move |ctx: CallCtx| {
                let handler = handler.clone();
                Box::pin(async move {
                    let max = ctx.max_encoding;
                    let resp = handler(request_stream(ctx)).await?;
                    Ok(stream_reply(resp, max))
                })
            }),
        )
    }

    /// Serves this server on `listener` (cleartext h2c, prior knowledge)
    /// until `shutdown` resolves, with [`GrpcServer::server_config`]. For
    /// TLS or other limits, pass the server to
    /// [`serve_with_config`](crate::http::serve_with_config) /
    /// [`serve_tls_with_config`](crate::http::serve_tls_with_config) with
    /// that configuration (or your own with `ServerConfig::http2` set).
    ///
    /// When `shutdown` resolves, the health service (if added) marks every
    /// service `NOT_SERVING` and ends its `Watch` streams, then connections
    /// drain. With `serve_with_config`, call
    /// [`HealthReporter::shutdown`](super::health::HealthReporter::shutdown)
    /// yourself first.
    pub async fn serve<F>(
        self,
        listener: tokio::net::TcpListener,
        shutdown: F,
    ) -> Result<(), HttpError>
    where
        F: Future<Output = ()> + Send,
    {
        let hooks = self.on_shutdown.clone();
        let shutdown = async move {
            shutdown.await;
            for hook in &hooks {
                hook();
            }
        };
        crate::http::serve_with_config(listener, Arc::new(self), shutdown, Self::server_config())
            .await
    }

    /// The server configuration [`serve`](Self::serve) uses: the
    /// [`ServerConfig`](crate::http::ServerConfig) defaults with HTTP/2 on
    /// and gRPC-appropriate HTTP/2 settings:
    /// [`stream_stall_timeout`](crate::http::Http2Config::stream_stall_timeout)
    /// off, so a client that reads a long-lived response stream slowly
    /// keeps it, and no per-connection stream cap
    /// ([`max_streams_per_connection`](crate::http::Http2Config::max_streams_per_connection)
    /// `None`, like grpc-go), and a
    /// [`rapid_reset_threshold`](crate::http::Http2Config::rapid_reset_threshold)
    /// of 10 ms: only a stream the client resets within 10 ms of opening it
    /// counts towards the hard rapid-reset budget
    /// ([`max_resets_per_window`](crate::http::Http2Config::max_resets_per_window)),
    /// so ordinary cancellations and deadline expiries, even of calls with
    /// deadlines of a few tens of milliseconds, never close the connection,
    /// while the attack pattern (resets right after HEADERS) still does.
    /// Resets of older calls that had not completed are bounded by
    /// [`max_cancels_per_window`](crate::http::Http2Config::max_cancels_per_window)
    /// (default: 1000 per 10 s, or twice the calls completed), so a client
    /// cannot sidestep the threshold by holding each call just past it.
    pub fn server_config() -> crate::http::ServerConfig {
        let h2 = crate::http::Http2Config {
            stream_stall_timeout: None,
            max_streams_per_connection: None,
            rapid_reset_threshold: Duration::from_millis(10),
            ..crate::http::Http2Config::default()
        };
        crate::http::ServerConfig {
            http2: Some(h2),
            ..crate::http::ServerConfig::default()
        }
    }

    /// The answer to a call whose interceptor or handler panicked:
    /// `INTERNAL`, with the panic text only for the `on_handler_panic` hook.
    fn panicked(&self, path: &str, content_type: &str, panic: &str) -> HttpResponse {
        if let Some(hook) = &self.on_panic {
            let _ = std::panic::catch_unwind(AssertUnwindSafe(|| hook(path, panic)));
        }
        early(
            StatusCode::OK,
            content_type,
            &Status::internal("the handler panicked"),
        )
    }

    async fn dispatch(&self, mut req: crate::http::Request) -> HttpResponse {
        let content_type = req.headers.get("content-type").unwrap_or("");
        let subtype_proto = match grpc_content_type(content_type) {
            Some(Ok(proto)) => proto,
            _ => {
                return early(
                    StatusCode(415),
                    "application/grpc",
                    &Status::internal(format!(
                        "invalid gRPC request content-type {content_type:?}"
                    )),
                )
            }
        };
        let content_type = if subtype_proto {
            "application/grpc+proto"
        } else {
            "application/grpc"
        };
        if req.protocol() != Protocol::Http2 {
            return early(
                StatusCode::BAD_REQUEST,
                content_type,
                &Status::internal("gRPC requires HTTP/2"),
            );
        }
        if req.method != Method::Post {
            return early(
                StatusCode(405),
                content_type,
                &Status::internal(format!(
                    "invalid gRPC request method {}",
                    req.method.as_str()
                )),
            );
        }
        let encoding = match req.headers.get("grpc-encoding") {
            None => Encoding::Identity,
            Some(value) => match Encoding::parse(value) {
                Some(encoding) => encoding,
                None => {
                    return early(
                        StatusCode::OK,
                        content_type,
                        &Status::unimplemented(format!(
                            "message encoding {value:?} is not supported \
                             (supported: {ACCEPT_ENCODING})"
                        )),
                    )
                }
            },
        };
        if self.require_te && !has_te_trailers(&req.headers) {
            return early(
                StatusCode::OK,
                content_type,
                &Status::internal("the request lacks te: trailers"),
            );
        }
        let timeout = match req.headers.get("grpc-timeout") {
            None => None,
            Some(raw) => match parse_timeout(raw.trim()) {
                Some(t) => Some(t),
                None => {
                    return early(
                        StatusCode::OK,
                        content_type,
                        &Status::internal(format!("malformed grpc-timeout {raw:?}")),
                    )
                }
            },
        };
        let path = req.uri.path.clone();
        let Some(route) = self.routes.get(&path).cloned() else {
            let status = match service_of(&path) {
                Some((service, method)) if self.services.contains(service) => {
                    Status::unimplemented(format!("unknown method {method} for service {service}"))
                }
                Some((service, _)) => Status::unimplemented(format!("unknown service {service}")),
                None => Status::unimplemented(format!("malformed method path {path:?}")),
            };
            return early(StatusCode::OK, content_type, &status);
        };
        let deadline = timeout.and_then(|t| Instant::now().checked_add(t));
        let body = match req.take_body_stream() {
            Some(body) => body,
            None => BodyStream::from_bytes(std::mem::take(&mut req.body)),
        };
        let peer = Peer {
            addr: req.peer_addr(),
            tls: req.is_tls(),
            certs: Arc::new(req.peer_certificates().to_vec()),
        };
        let mut metadata = Metadata::from_headers(&req.headers);
        drop(req);
        if !self.interceptors.is_empty() {
            let mut head = Request::from_server(
                (),
                metadata,
                timeout,
                deadline.map(Instant::into_std),
                peer.clone(),
            );
            // An interceptor is caller code too: a panic in it ends the call
            // like a handler's.
            let intercepted = std::panic::catch_unwind(AssertUnwindSafe(|| {
                interceptor::run(&self.interceptors, &path, &mut head)
            }));
            match intercepted {
                Ok(Ok(())) => {}
                Ok(Err(status)) => return early(StatusCode::OK, content_type, &status),
                Err(payload) => {
                    return self.panicked(&path, content_type, &panic_message(payload));
                }
            }
            metadata = head.into_parts().0;
        }
        let ctx = CallCtx {
            metadata,
            timeout,
            deadline,
            peer,
            body,
            receive: Receive {
                max_size: self.max_decoding,
                limits: decode_limits(self.max_decoding, self.max_decoded_bytes),
                encoding,
            },
            max_encoding: self.max_encoding,
        };

        let call = CatchUnwind(route(ctx));
        let outcome = match deadline {
            Some(deadline) => match tokio::time::timeout_at(deadline, call).await {
                Ok(outcome) => outcome,
                Err(_) => Ok(Err(Status::deadline_exceeded("the deadline passed"))),
            },
            None => call.await,
        };
        let reply = match outcome {
            Ok(Ok(reply)) => reply,
            Ok(Err(status)) => return early(StatusCode::OK, content_type, &status),
            Err(panic) => return self.panicked(&path, content_type, &panic),
        };
        let mut resp = HttpResponse::new(StatusCode::OK)
            .header("content-type", content_type)
            .header("grpc-accept-encoding", ACCEPT_ENCODING);
        match reply {
            Reply::Unary {
                metadata,
                frame,
                trailers,
            } => {
                metadata.write_to(&mut resp.headers);
                let mut t = HeaderMap::new();
                Status::ok().with_metadata(trailers).write_to(&mut t);
                resp.body(frame).with_trailers(t)
            }
            Reply::Stream {
                metadata,
                mut source,
                trailers,
            } => {
                let (mut tx, rx) = body_channel(4);
                let on_panic = self.on_panic.clone();
                tokio::spawn(async move {
                    // The pump runs the handler's stream and the response
                    // messages' `encode`: user code, whose panic must still
                    // end the call with trailers.
                    let pumped = CatchUnwind(Box::pin(async {
                        let end = pump(&mut *source, &mut tx, deadline).await;
                        // Stop reading the handler's stream before the
                        // trailers go out, so its senders see the end.
                        drop(source);
                        end
                    }))
                    .await;
                    let status = match pumped {
                        Ok(PumpEnd::Done) => Status::ok().with_metadata(trailers),
                        Ok(PumpEnd::Failed(status)) => status,
                        Ok(PumpEnd::ReaderGone) => return,
                        Err(panic) => {
                            if let Some(hook) = &on_panic {
                                let _ = std::panic::catch_unwind(AssertUnwindSafe(|| {
                                    hook(&path, &panic)
                                }));
                            }
                            Status::internal("the handler panicked")
                        }
                    };
                    let mut t = HeaderMap::new();
                    status.write_to(&mut t);
                    let _ = tx.send_trailers(t).await;
                });
                let mut resp = HttpResponse::body_stream(StatusCode::OK, rx)
                    .header("content-type", content_type)
                    .header("grpc-accept-encoding", ACCEPT_ENCODING);
                metadata.write_to(&mut resp.headers);
                resp
            }
        }
    }
}

/// `Some(Ok(true))` for `application/grpc+proto`, `Some(Ok(false))` for
/// `application/grpc`, `Some(Err(()))` for another `application/grpc+…`
/// subtype, `None` when it is not gRPC at all.
#[allow(clippy::result_unit_err)]
pub(crate) fn grpc_content_type(value: &str) -> Option<Result<bool, ()>> {
    let essence = value.split(';').next().unwrap_or("").trim();
    let essence = essence.to_ascii_lowercase();
    match essence.strip_prefix("application/grpc")? {
        "" => Some(Ok(false)),
        "+proto" => Some(Ok(true)),
        sub if sub.starts_with('+') => Some(Err(())),
        _ => None,
    }
}

/// Whether the request says it accepts trailers (`te: trailers`).
fn has_te_trailers(headers: &HeaderMap) -> bool {
    headers.get_all("te").any(|te| {
        te.split(',')
            .any(|t| t.trim().eq_ignore_ascii_case("trailers"))
    })
}

/// A trailers-only response: the status in the response headers, no body.
fn early(http: StatusCode, content_type: &str, status: &Status) -> HttpResponse {
    let mut resp = HttpResponse::new(http)
        .header("content-type", content_type)
        .header("grpc-accept-encoding", ACCEPT_ENCODING);
    status.write_to(&mut resp.headers);
    resp
}

/// Reads exactly one request message.
async fn read_one<M: Message>(ctx: &mut CallCtx) -> Result<M, Status> {
    let body = std::mem::replace(&mut ctx.body, BodyStream::empty());
    let mut wire = Wire::new(Source::Server(body), ctx.receive, ctx.deadline);
    let first = wire.next_frame().await?.ok_or_else(|| {
        Status::internal("the request has no message (a unary request needs one)")
    })?;
    if wire.next_frame().await?.is_some() {
        return Err(Status::internal(
            "the request has more than one message (a unary request has one)",
        ));
    }
    decode_message(&first, ctx.receive.limits)
}

fn request_stream<M>(ctx: CallCtx) -> Request<Streaming<M>> {
    let CallCtx {
        metadata,
        timeout,
        deadline,
        peer,
        body,
        receive,
        ..
    } = ctx;
    let stream = Streaming::wire(Wire::new(Source::Server(body), receive, deadline));
    Request::from_server(
        stream,
        metadata,
        timeout,
        deadline.map(Instant::into_std),
        peer,
    )
}

fn unary_reply<M: Message>(resp: Response<M>, max: usize) -> Result<Reply, Status> {
    let (metadata, message, trailers) = resp.into_parts();
    Ok(Reply::Unary {
        metadata,
        frame: encode_frame(&message, max)?,
        trailers,
    })
}

fn stream_reply<M: Message + Send + 'static>(resp: Response<Streaming<M>>, max: usize) -> Reply {
    let (metadata, stream, trailers) = resp.into_parts();
    Reply::Stream {
        metadata,
        source: Box::new(Encoder {
            stream,
            max_size: max,
        }),
        trailers,
    }
}

impl HttpHandler for GrpcServer {
    fn handle(&self, req: crate::http::Request) -> BoxFuture<'_, HttpResponse> {
        if let Some(fallback) = &self.fallback {
            if !is_grpc(&req) {
                return fallback.handle(req);
            }
        }
        Box::pin(self.dispatch(req))
    }

    fn wants_body_stream(&self, req: &crate::http::Request) -> bool {
        match &self.fallback {
            Some(fallback) if !is_grpc(req) => fallback.wants_body_stream(req),
            _ => true,
        }
    }
}

fn is_grpc(req: &crate::http::Request) -> bool {
    grpc_content_type(req.headers.get("content-type").unwrap_or("")).is_some()
}

/// Polls a handler future, turning a panic into an error (the panic
/// message) instead of letting it unwind into the connection task.
struct CatchUnwind<F>(F);

impl<T, F: Future<Output = T> + Unpin> Future for CatchUnwind<F> {
    type Output = Result<T, String>;

    fn poll(mut self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<Self::Output> {
        let future = &mut self.0;
        match std::panic::catch_unwind(AssertUnwindSafe(|| Pin::new(future).poll(cx))) {
            Ok(Poll::Ready(v)) => Poll::Ready(Ok(v)),
            Ok(Poll::Pending) => Poll::Pending,
            Err(payload) => Poll::Ready(Err(panic_message(payload))),
        }
    }
}

fn panic_message(payload: Box<dyn std::any::Any + Send>) -> String {
    if let Some(s) = payload.downcast_ref::<&str>() {
        (*s).to_string()
    } else if let Some(s) = payload.downcast_ref::<String>() {
        s.clone()
    } else {
        "non-string panic payload".to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn content_types_and_paths() {
        assert_eq!(grpc_content_type("application/grpc"), Some(Ok(false)));
        assert_eq!(grpc_content_type("Application/GRPC+proto"), Some(Ok(true)));
        assert_eq!(
            grpc_content_type("application/grpc; charset=utf-8"),
            Some(Ok(false))
        );
        assert_eq!(grpc_content_type("application/grpc+json"), Some(Err(())));
        assert_eq!(grpc_content_type("application/grpc-web"), None);
        assert_eq!(grpc_content_type("application/json"), None);
        assert_eq!(grpc_content_type(""), None);
        assert_eq!(service_of("/a.B/C"), Some(("a.B", "C")));
        for bad in ["", "/", "a.B/C", "/a.B", "/a.B/", "//C", "/a/b/c"] {
            assert_eq!(service_of(bad), None, "{bad:?}");
        }
    }
}
